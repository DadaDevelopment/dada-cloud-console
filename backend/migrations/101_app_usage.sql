-- 101_app_usage.sql
--
-- Часовой журнал потребления пользовательских приложений. Ответ на вопрос,
-- на который до сих пор нельзя было ответить задним числом: сколько стоил
-- конкретный апп конкретного клиента в конкретный час.
--
-- До этой таблицы платформа умела считать только run-rate «прямо сейчас»
-- (OpenCost-снапшот за 24h, спроецированный на месяц, billing_fullcost.go).
-- Run-rate не журнал: он не помнит вчера, он умирает вместе с ретеншном
-- метрик, и по нему нельзя ни выставить overage, ни разобрать спор о счёте,
-- ни увидеть, что апп сутки держал четыре реплики и был удалён.
--
-- Форма скопирована с box_usage (063) намеренно — там она уже отработала на
-- боксах, и три её свойства несут весь смысл:
--
--   1. PK (environment_id, app_name, hour_start, kind) — якорь идемпотентности.
--      Метр крутится НЕЗАЩИЩЁННО на каждой реплике бэкенда, как и боксовый:
--      повтор тика, упавший под и гонка двух реплик схлопываются в одну
--      строку. Advisory lock здесь был бы хуже — обе реплики всё равно берут
--      лок (см. tasks/lessons.md), а отказ одной реплики превратился бы в
--      непроверяемую дыру в журнале.
--
--   2. ЧАС БЕЗ ПОТРЕБЛЕНИЯ НЕ ПИШЕТ СТРОКУ ВООБЩЕ. Не строку с нулём.
--      Отсутствие строки — единственная форма утверждения «не потреблял»,
--      которую нельзя молча развернуть правкой YAML: нулевую строку можно
--      начать тарифицировать, несуществующую надо сначала создать кодом,
--      который кто-то напишет и отревьюит.
--
--   3. cost_rub ЗАМОРОЖЕН НА МОМЕНТ ЗАПИСИ. Цена выводится из cluster-cost.yaml
--      + overhead-факторов + маржи, а все три двигаются. Пересчёт истории по
--      сегодняшним входам молча переписал бы прошлый месяц. Футпринт, из
--      которого получена цена, лежит рядом, поэтому любую строку можно
--      перевыставить и проаудировать, не гадая, какой прайс был жив тогда.
--
-- ЧТО ИМЕННО ТАРИФИЦИРУЕТСЯ (решение владельца, 2026-08-04: «факт», «под +
-- тома», «бд — отдельный ресурс и платится она отдельно»):
--
--   vcpu/ram_gb — то, что кластер РЕАЛЬНО ДЕРЖАЛ под этот апп: requests
--   запущенных подов, просуммированные по фактически живым репликам и
--   усреднённые по часу. Не профиль из БД (это была бы «заявка», владелец
--   выбрал факт) и не фактическая утилизация. Утилизация как база тарификации
--   — подарок: замер на проде показал апп с held 0.04 ядра и used 0.0026, то
--   есть по утилизации клиент заплатил бы 6% от того, что кластер под него
--   зарезервировал и не смог продать никому другому. Утилизация всё равно
--   пишется, но в used_* — это столбец про маржу и переподписку, НЕ база счёта.
--
--   storage_gb — provisioned-размер PVC, привязанных к подам аппа. Именно
--   provisioned, а не заполненный: Longhorn держит весь том целиком.
--
--   Managed DB здесь НЕТ. Это отдельный ресурс с отдельным счётом
--   (consumptionDatabases), и его доля шареного postgres-пода считается по
--   размеру на диске. Затащить его сюда значило бы посчитать дважды.
--
-- РЕТЕНШН 30 дней (владелец: «30 дней хватает»). Прунит сам метр. При сотне
-- аппов это ~2 строки/час/апп x 720 x 100 = 144k строк — на два порядка легче
-- поминутного боксового журнала, что существенно для базы, которая ложилась
-- по ENOSPC.

CREATE TABLE IF NOT EXISTS app_usage (
    -- Идентичность аппа. environment_id БЕЗ внешнего ключа, ровно по той же
    -- причине, что box_usage.box_id: удаление проекта каскадится в
    -- environments, а ON DELETE CASCADE здесь стёр бы запись о том, что
    -- клиент потребил, в тот самый момент, когда он это потребление
    -- закончил. Журнал, исчезающий вместе со своим субъектом, не может
    -- закрыть спор о счёте. Осиротевшие строки — приемлемая сторона размена.
    environment_id UUID        NOT NULL,
    app_name       TEXT        NOT NULL,
    hour_start     TIMESTAMPTZ NOT NULL,
    -- 'pod' | 'volume'. Без CHECK — по той же причине, что в box_usage: метр
    -- единственный писатель и пишет ровно два значения, а CHECK пришлось бы
    -- расширять раньше, чем появится третий вид ресурса.
    kind           TEXT        NOT NULL,

    -- Аренда, денормализована НАМЕРЕННО: строка обязана оставаться
    -- атрибутируемой после того, как апп, окружение и проект удалены (см.
    -- отсутствие FK выше). org_id TEXT под projects.org_id / billing_accounts.
    org_id     TEXT NOT NULL DEFAULT '',
    project_id UUID,
    namespace  TEXT NOT NULL DEFAULT '',

    -- Оплачиваемый футпринт часа, замороженный. NUMERIC, никогда не float:
    -- эти столбцы суммируются в счёт, а двоичная плавающая точка копит дрейф,
    -- из-за которого одна и та же сумма зависит от порядка строк.
    vcpu       NUMERIC(10,4) NOT NULL DEFAULT 0,
    ram_gb     NUMERIC(10,4) NOT NULL DEFAULT 0,
    storage_gb NUMERIC(10,4) NOT NULL DEFAULT 0,
    -- Среднее число ЖИВЫХ реплик за час, дробное. Апп, поднявший вторую
    -- реплику на двадцать минут, честно стоит 1.33. Столбец объясняющий:
    -- vcpu уже просуммирован по репликам, здесь лежит множитель, которым
    -- строку можно прочитать вслух («small x 2 реплики»).
    replicas   NUMERIC(8,3)  NOT NULL DEFAULT 0,

    -- Наблюдаемая утилизация. NULL значит «метрики не дали ответа», и это
    -- отличается от измеренного нуля. НЕ база тарификации, см. шапку.
    used_vcpu   NUMERIC(10,4),
    used_ram_gb NUMERIC(10,4),

    -- Шесть знаков: час small-аппа — доли копейки, округление до двух
    -- обнулило бы большинство строк и журнал сложился бы в ничто.
    cost_rub NUMERIC(14,6) NOT NULL DEFAULT 0,

    -- Когда метр записал строку, в отличие от часа, который она описывает.
    -- Разрыв между ними — отставание метра.
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (environment_id, app_name, hour_start, kind)
);

-- Разбор по проекту и по орге: обе выборки идут окном по времени, а PK
-- начинается с environment_id и для них бесполезен.
CREATE INDEX IF NOT EXISTS idx_app_usage_project_hour
    ON app_usage (project_id, hour_start DESC)
    WHERE project_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_app_usage_org_hour
    ON app_usage (org_id, hour_start DESC);
-- Прун ретеншна сканирует ровно по этому столбцу.
CREATE INDEX IF NOT EXISTS idx_app_usage_hour
    ON app_usage (hour_start);

GRANT SELECT, INSERT, UPDATE, DELETE ON app_usage TO dada;
