-- 102_app_usage_source.sql
--
-- Откуда взялась строка журнала: измерил ли её метр по горячим следам или
-- восстановил бэкфилл задним числом.
--
-- Журнал (101) появился 2026-08-04 и умеет отвечать только про часы после
-- своего рождения. Вопрос владельца был про другое: «он так и не заплатит за
-- всё, что наюзал?» — то есть про недели ДО. Метрики на это ответить могут:
-- локальный prometheus живёт три дня, но remote_write отправляет
-- kube-state-метрики в Mimir под тенантом opencost, и там они лежат около трёх
-- недель. Бэкфилл читает ровно эти ряды теми же выражениями, что и метр.
--
-- Столбец нужен потому, что восстановленный час НЕ РАВЕН измеренному, и разница
-- не косметическая:
--
--   1. Цена. cost_rub морозится на момент ЗАПИСИ (см. 101). Метр пишет час
--      через час после его конца, по прайсу, живому тогда. Бэкфилл пишет
--      трёхнедельной давности час по СЕГОДНЯШНЕМУ прайсу. Это единственно
--      возможный ответ (прошлый прайс никто не сохранял), но выдавать его за
--      замер — врать. Футпринт при этом настоящий, поэтому строку всегда можно
--      перевыставить по любому прайсу.
--
--   2. Фильтр «под реально работал». Метр берёт kube_pod_status_phase, которого
--      в Mimir нет — remote_write его не пересылает. Бэкфилл берёт
--      kube_pod_container_status_running. Это близкие, но не тождественные
--      утверждения о поде.
--
-- Поэтому спор о счёте, упершийся в строку source='backfill', разрешается в
-- пользу клиента, а не платформы, и по столбцу это видно без археологии.
--
-- Направление перезаписи однозначно: замер побеждает реконструкцию. Метр
-- продолжает upsert'ить и проставляет source='meter' поверх; бэкфилл пишет
-- ON CONFLICT DO NOTHING и не трогает то, что уже измерено.
--
-- DEFAULT 'meter' для существующих строк корректен: на момент миграции журнал
-- писал только метр.

ALTER TABLE app_usage
    ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'meter';
