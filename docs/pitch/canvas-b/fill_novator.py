def set_text(shape, text):
    tf = shape.text_frame
    p0 = tf.paragraphs[0]
    runs = p0.runs
    if not runs:
        tf.text = text
        return
    proto = copy.deepcopy(runs[0]._r)
    for r in runs[1:]:
        r._r.getparent().remove(r._r)
    for p in tf.paragraphs[1:]:
        p._p.getparent().remove(p._p)
    lines = text.split("\n")
    runs[0].text = lines[0]
    for line in lines[1:]:
        np = copy.deepcopy(p0._p)
        for r in np.findall(".//{http://schemas.openxmlformats.org/drawingml/2006/main}r")[1:]:
            r.getparent().remove(r)
        p0._p.getparent().append(np)
        from pptx.text.text import _Paragraph
        par = _Paragraph(np, tf)
        if par.runs:
            par.runs[0].text = line
        else:
            par.text = line
    del proto


def walk(shapes):
    for sh in shapes:
        yield sh
        if sh.shape_type == 6:
            for x in walk(sh.shapes):
                yield x


pres = Presentation(SRC)
touched = set()
for idx, slide in enumerate(pres.slides, 1):
    for sh in walk(slide.shapes):
        if sh.shape_id in PAGENUM and sh.has_text_frame:
            set_text(sh, PAGENUM[sh.shape_id])
        if sh.shape_id in TEXT and sh.has_text_frame:
            set_text(sh, TEXT[sh.shape_id])
            touched.add(sh.shape_id)
        if sh.has_table and idx == 10:
            t = sh.table
            for ri, row in enumerate(TABLE):
                for ci, val in enumerate(row):
                    cell = t.cell(ri, ci)
                    set_text(cell, val)
    for sh in list(walk(slide.shapes)):
        if sh.shape_id in DROP_SHAPES.get(idx, []):
            sh._element.getparent().remove(sh._element)

missing = sorted(set(TEXT) - touched)
if missing:
    print("NOT FOUND:", missing)

xml_slides = pres.slides._sldIdLst
ids = list(xml_slides)
for n in sorted(DROP_SLIDES, reverse=True):
    rid = ids[n - 1].get("{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id")
    pres.part.drop_rel(rid)
    xml_slides.remove(ids[n - 1])

pres.save(DST)
